import {
  BadRequestException,
  Body,
  Controller,
  Headers,
  Post,
  Req,
} from '@nestjs/common';
import type { Request } from 'express';
import { Public } from '../common/auth/decorators/public.decorator.js';
import { BillingService } from './billing.service.js';
import {
  ApiHeader,
  ApiBody,
  ApiOperation,
  ApiResponse,
  ApiTags,
} from '@nestjs/swagger';

@ApiTags('Billing')
@Controller('webhooks')
export class BillingWebhookController {
  constructor(private readonly billing: BillingService) {}

  @Public()
  @Post('razorpay')
  @ApiOperation({ summary: 'Process a Razorpay webhook' })
  @ApiHeader({
    name: 'x-razorpay-signature',
    required: true,
    description:
      'HMAC signature of the raw request body, generated by Razorpay.',
  })
  @ApiHeader({
    name: 'x-razorpay-event-id',
    required: true,
    description: 'Unique identifier for the Razorpay webhook delivery.',
  })
  @ApiBody({
    schema: {
      type: 'object',
      required: ['event', 'account_id', 'created_at'],
      properties: {
        event: { type: 'string' },
        account_id: { type: 'string' },
        created_at: { type: 'integer' },
        payload: {
          type: 'object',
          properties: {
            subscription: {
              type: 'object',
              properties: {
                entity: {
                  type: 'object',
                  properties: {
                    id: { type: 'string' },
                    current_start: { type: 'integer' },
                    current_end: { type: 'integer' },
                    notes: {
                      type: 'object',
                      properties: { plan: { type: 'string' } },
                    },
                  },
                },
              },
            },
            payment: {
              type: 'object',
              properties: {
                entity: {
                  type: 'object',
                  properties: { id: { type: 'string' } },
                },
              },
            },
          },
        },
      },
    },
  })
  @ApiResponse({
    status: 201,
    description:
      'Acknowledges a verified webhook; duplicate deliveries include duplicate=true.',
    schema: {
      type: 'object',
      required: ['accepted'],
      properties: {
        accepted: { type: 'boolean', enum: [true] },
        duplicate: { type: 'boolean' },
      },
    },
  })
  webhook(
    @Req() request: Request & { rawBody?: Buffer },
    @Headers('x-razorpay-signature') signature: string,
    @Headers('x-razorpay-event-id') eventId: string | undefined,
    @Body() payload: Parameters<BillingService['processWebhook']>[3],
  ) {
    if (!request.rawBody) {
      throw new BadRequestException(
        'Raw webhook body is required for signature verification',
      );
    }
    return this.billing.processWebhook(
      request.rawBody,
      signature,
      eventId,
      payload,
    );
  }
}
